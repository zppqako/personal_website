(function() {
  // ===== NAV SCROLL =====
  const nav = document.getElementById('navbar');
  window.addEventListener('scroll', () => {
    nav.classList.toggle('scrolled', window.scrollY > 80);
  });

  // ===== MOBILE MENU =====
  const menuToggle = document.getElementById('menuToggle');
  const mobileMenu = document.getElementById('mobileMenu');

  menuToggle.addEventListener('click', () => {
    menuToggle.classList.toggle('open');
    mobileMenu.classList.toggle('open');
    document.body.style.overflow = mobileMenu.classList.contains('open') ? 'hidden' : '';
  });

  mobileMenu.querySelectorAll('a').forEach(link => {
    link.addEventListener('click', () => {
      menuToggle.classList.remove('open');
      mobileMenu.classList.remove('open');
      document.body.style.overflow = '';
    });
  });

  // ===== GALLERY =====
  // Photos come from data/photos.json (generated by scripts/process_photos.py).
  const galleryGrid = document.getElementById('galleryGrid');
  const GALLERY_SIZES = '(max-width: 480px) calc(100vw - 32px), (max-width: 1024px) calc(50vw - 48px), min(30vw, 500px)';
  let galleryItems = [];

  function photoWidth(photo, longEdge) {
    const scale = Math.min(1, longEdge / Math.max(photo.width, photo.height));
    return Math.round(photo.width * scale);
  }

  function renderGallery(photos) {
    photos.filter(photo => !photo.hidden).forEach(photo => {
      const base = 'photos/' + photo.id;
      const item = document.createElement('div');
      item.className = 'gallery-item';
      item.dataset.full = base + '-' + photo.sizes[photo.sizes.length - 1] + '.webp';
      item.dataset.ratio = photo.height / photo.width;

      const picture = document.createElement('picture');
      const source = document.createElement('source');
      source.type = 'image/webp';
      source.srcset = photo.sizes.map(s => `${base}-${s}.webp ${photoWidth(photo, s)}w`).join(', ');
      source.sizes = GALLERY_SIZES;
      const img = document.createElement('img');
      img.src = base + '.jpg';
      img.width = photo.width;
      img.height = photo.height;
      img.alt = (photo.alt && (photo.alt.en || photo.alt.zh)) || 'Photo';
      img.loading = 'lazy';
      picture.append(source, img);

      const overlay = document.createElement('div');
      overlay.className = 'gallery-overlay';
      item.append(picture, overlay);
      galleryItems.push(item);
    });
    layoutGallery();
  }

  // Masonry that reads left to right: photo 1, 2, 3 form the first row, then each
  // photo goes into the currently shortest column. The last few photos are placed
  // to keep the bottom edge even. Column count comes from the --gallery-columns
  // CSS variable, so breakpoints live only in style.css.
  const BALANCE_TAIL = 8;
  let currentColumns = 0;

  function layoutGallery() {
    const style = getComputedStyle(galleryGrid);
    const count = parseInt(style.getPropertyValue('--gallery-columns'), 10) || 1;
    if (count === currentColumns) return;
    currentColumns = count;

    // Heights in units of column width; the space below each photo equals the column gap.
    const gap = parseFloat(style.columnGap) || 0;
    const inner = galleryGrid.clientWidth - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight);
    const spacing = gap / ((inner - gap * (count - 1)) / count);
    const cost = item => Number(item.dataset.ratio) + spacing;

    const placement = [];
    const heights = new Array(count).fill(0);
    const tail = count > 1 ? Math.min(BALANCE_TAIL, galleryItems.length) : 0;
    const head = galleryItems.length - tail;
    for (let i = 0; i < head; i++) {
      const shortest = heights.indexOf(Math.min(...heights));
      placement.push(shortest);
      heights[shortest] += cost(galleryItems[i]);
    }

    // Try every way to place the tail and keep the one with the flattest bottom.
    let best = [], bestSpread = Infinity;
    for (let combo = 0; combo < count ** tail; combo++) {
      const h = heights.slice(), choice = [];
      for (let k = 0, c = combo; k < tail; k++, c = Math.floor(c / count)) {
        choice.push(c % count);
        h[c % count] += cost(galleryItems[head + k]);
      }
      const spread = Math.max(...h) - Math.min(...h);
      if (spread < bestSpread - 1e-6) { bestSpread = spread; best = choice; }
    }
    placement.push(...best);

    const columns = Array.from({ length: count }, () => {
      const col = document.createElement('div');
      col.className = 'gallery-column';
      return col;
    });
    galleryItems.forEach((item, i) => columns[placement[i]].appendChild(item));
    galleryGrid.replaceChildren(...columns);
  }

  window.addEventListener('resize', layoutGallery);

  // ===== LIGHTBOX =====
  const lightbox = document.getElementById('lightbox');
  const lightboxImg = document.getElementById('lightboxImg');
  let currentIndex = 0;

  function showInLightbox(item) {
    lightboxImg.src = item.dataset.full;
    lightboxImg.alt = item.querySelector('img').alt;
  }

  function openLightbox(index) {
    currentIndex = index;
    showInLightbox(galleryItems[currentIndex]);
    lightbox.classList.add('active');
    document.body.style.overflow = 'hidden';
  }

  function closeLightbox() {
    lightbox.classList.remove('active');
    document.body.style.overflow = '';
  }

  function navigate(dir) {
    currentIndex = (currentIndex + dir + galleryItems.length) % galleryItems.length;
    showInLightbox(galleryItems[currentIndex]);
  }

  galleryGrid.addEventListener('click', (e) => {
    const item = e.target.closest('.gallery-item');
    if (item) openLightbox(Math.max(0, galleryItems.indexOf(item)));
  });

  lightbox.querySelector('.lightbox-close').addEventListener('click', closeLightbox);
  lightbox.querySelector('.lightbox-prev').addEventListener('click', (e) => { e.stopPropagation(); navigate(-1); });
  lightbox.querySelector('.lightbox-next').addEventListener('click', (e) => { e.stopPropagation(); navigate(1); });
  lightbox.addEventListener('click', (e) => { if (e.target === lightbox) closeLightbox(); });

  document.addEventListener('keydown', (e) => {
    if (!lightbox.classList.contains('active')) return;
    if (e.key === 'Escape') closeLightbox();
    if (e.key === 'ArrowLeft') navigate(-1);
    if (e.key === 'ArrowRight') navigate(1);
  });

  // ===== SCROLL REVEAL =====
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add(entry.target.classList.contains('gallery-item') ? 'visible' : 'revealed');
      }
    });
  }, { threshold: 0.1, rootMargin: '0px 0px -40px 0px' });

  function initReveal() {
    document.querySelectorAll('.reveal, .gallery-item').forEach((el, i) => {
      if (el.classList.contains('gallery-item')) {
        el.style.transitionDelay = ((galleryItems.indexOf(el) + 1) * 0.08) + 's';
      }
      observer.observe(el);
    });
  }

  fetch('data/photos.json')
    .then(res => res.json())
    .then(data => renderGallery(data.photos))
    .catch(err => console.error('Could not load data/photos.json', err))
    .finally(initReveal);

  // ===== ACTIVE NAV LINK =====
  const sections = document.querySelectorAll('section[id]');
  const navLinks = document.querySelectorAll('.nav-links a');

  window.addEventListener('scroll', () => {
    let current = '';
    sections.forEach(section => {
      const top = section.offsetTop - 200;
      if (window.scrollY >= top) current = section.getAttribute('id');
    });
    navLinks.forEach(link => {
      link.classList.toggle('active', link.getAttribute('href') === '#' + current);
    });
  });

  // ===== LANGUAGE TOGGLE =====
  const langToggle = document.getElementById('langToggle');
  let currentLang = localStorage.getItem('lang') || 'en';
  const enTextStore = new Map();
  const enHtmlStore = new Map();

  document.querySelectorAll('[data-zh]').forEach(el => {
    enTextStore.set(el, el.textContent);
  });
  document.querySelectorAll('[data-zh-html]').forEach(el => {
    enHtmlStore.set(el, el.innerHTML);
  });

  function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('lang', lang);
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    document.title = lang === 'zh' ? '作品集 — 摄影' : 'Portfolio \u2014 Photography';
    langToggle.textContent = lang === 'zh' ? 'EN' : '\u4E2D\u6587';

    document.querySelectorAll('[data-zh]').forEach(el => {
      el.textContent = lang === 'zh' ? el.dataset.zh : enTextStore.get(el);
    });

    document.querySelectorAll('[data-zh-html]').forEach(el => {
      el.innerHTML = lang === 'zh' ? el.dataset.zhHtml : enHtmlStore.get(el);
    });

  }

  langToggle.addEventListener('click', () => {
    setLanguage(currentLang === 'en' ? 'zh' : 'en');
  });

  if (currentLang === 'zh') setLanguage('zh');
})();
