(function() {
  // ===== NAV SCROLL =====
  const nav = document.getElementById('navbar');
  window.addEventListener('scroll', () => {
    nav.classList.toggle('scrolled', window.scrollY > 80);
  });

  // ===== MOBILE MENU =====
  const menuToggle = document.getElementById('menuToggle');
  const mobileMenu = document.getElementById('mobileMenu');

  menuToggle.addEventListener('click', () => {
    menuToggle.classList.toggle('open');
    mobileMenu.classList.toggle('open');
    document.body.style.overflow = mobileMenu.classList.contains('open') ? 'hidden' : '';
  });

  mobileMenu.querySelectorAll('a').forEach(link => {
    link.addEventListener('click', () => {
      menuToggle.classList.remove('open');
      mobileMenu.classList.remove('open');
      document.body.style.overflow = '';
    });
  });

  // ===== GALLERY =====
  // Photos come from data/photos.json (generated by scripts/process_photos.py).
  const galleryGrid = document.getElementById('galleryGrid');
  const GALLERY_SIZES = '(max-width: 480px) calc(100vw - 32px), (max-width: 1024px) calc(50vw - 48px), min(30vw, 500px)';
  let galleryItems = [];

  function photoWidth(photo, longEdge) {
    const scale = Math.min(1, longEdge / Math.max(photo.width, photo.height));
    return Math.round(photo.width * scale);
  }

  // One quiet line under the photo in the lightbox, like a gallery wall label.
  function captionFor(exif) {
    if (!exif) return '';
    const camera = exif.camera || '';
    const model = camera.split(' ').slice(1).join(' ') || camera;
    const lens = exif.lens && !(model && exif.lens.includes(model)) ? exif.lens : ''; // skip "iPhone … back camera"
    return [
      camera,
      lens,
      exif.focalLength && exif.focalLength + 'mm',
      exif.aperture && '\u0192/' + exif.aperture,
      exif.shutter,
      exif.iso && 'ISO ' + exif.iso,
    ].filter(Boolean).map(part => String(part).replace(/ /g, '\u00a0')).join('  \u00b7  '); // wrap only between parts
  }

  const EAGER_COUNT = 3; // first row on desktop: load immediately, not lazily

  function renderGallery(photos) {
    photos.forEach((photo, index) => {
      const base = 'photos/' + photo.id;
      // HDR photos use JPEG + gain map (WebP cannot carry HDR); the rest use WebP.
      const file = size => photo.hdr ? `${base}-${size}-hdr.jpg` : `${base}-${size}.webp`;
      const srcset = photo.sizes.map(size => `${file(size)} ${photoWidth(photo, size)}w`).join(', ');
      const label = photo.title || 'Photograph';
      const item = document.createElement('div');
      item.className = 'gallery-item';
      item.tabIndex = 0;
      item.setAttribute('role', 'button');
      item.setAttribute('aria-label', label);
      item.dataset.id = photo.id;
      item.dataset.full = file(photo.sizes[photo.sizes.length - 1]);
      item.dataset.ratio = photo.height / photo.width;
      item.dataset.title = photo.title || '';
      item.dataset.caption = captionFor(photo.exif);

      const picture = document.createElement('picture');
      const source = document.createElement('source');
      source.type = photo.hdr ? 'image/jpeg' : 'image/webp';
      source.srcset = srcset;
      source.sizes = GALLERY_SIZES;
      const img = document.createElement('img');
      img.src = base + '.jpg';
      img.width = photo.width;
      img.height = photo.height;
      img.alt = label;
      if (index < EAGER_COUNT) {
        img.fetchPriority = 'high';
      } else {
        img.loading = 'lazy';
      }
      picture.append(source, img);
      item.appendChild(picture);
      galleryItems.push(item);
    });
    layoutGallery();
  }

  // Masonry that reads left to right: photo 1, 2, 3 form the first row, then each
  // photo goes into the currently shortest column. The last few photos are placed
  // to keep the bottom edge even. Column count comes from the --gallery-columns
  // CSS variable, so breakpoints live only in style.css.
  const BALANCE_TAIL = 8;
  let currentColumns = 0;

  function layoutGallery() {
    const style = getComputedStyle(galleryGrid);
    const count = parseInt(style.getPropertyValue('--gallery-columns'), 10) || 1;
    if (count === currentColumns) return;
    currentColumns = count;

    // Heights in units of column width; the space below each photo equals the column gap.
    const gap = parseFloat(style.columnGap) || 0;
    const inner = galleryGrid.clientWidth - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight);
    const spacing = gap / ((inner - gap * (count - 1)) / count);
    const cost = item => Number(item.dataset.ratio) + spacing;

    const placement = [];
    const heights = new Array(count).fill(0);
    const tail = count > 1 ? Math.min(BALANCE_TAIL, galleryItems.length) : 0;
    const head = galleryItems.length - tail;
    for (let i = 0; i < head; i++) {
      const shortest = heights.indexOf(Math.min(...heights));
      placement.push(shortest);
      heights[shortest] += cost(galleryItems[i]);
    }

    // Try every way to place the tail and keep the one with the flattest bottom.
    let best = [], bestSpread = Infinity;
    for (let combo = 0; combo < count ** tail; combo++) {
      const h = heights.slice(), choice = [];
      for (let k = 0, c = combo; k < tail; k++, c = Math.floor(c / count)) {
        choice.push(c % count);
        h[c % count] += cost(galleryItems[head + k]);
      }
      const spread = Math.max(...h) - Math.min(...h);
      if (spread < bestSpread - 1e-6) { bestSpread = spread; best = choice; }
    }
    placement.push(...best);

    const columns = Array.from({ length: count }, () => {
      const col = document.createElement('div');
      col.className = 'gallery-column';
      return col;
    });
    galleryItems.forEach((item, i) => columns[placement[i]].appendChild(item));
    galleryGrid.replaceChildren(...columns);
  }

  window.addEventListener('resize', layoutGallery);

  // ===== LIGHTBOX =====
  // Each open photo gets its own address (#DSCF5010): links to a single photo work,
  // and the phone's back button closes the viewer instead of leaving the site.
  const lightbox = document.getElementById('lightbox');
  const lightboxImg = document.getElementById('lightboxImg');
  const lightboxTitle = document.getElementById('lightboxTitle');
  const lightboxCaption = document.getElementById('lightboxCaption');
  const lightboxCounter = document.getElementById('lightboxCounter');
  let currentIndex = -1;
  let returnFocus = null;

  function preload(index) {
    const item = galleryItems[(index + galleryItems.length) % galleryItems.length];
    if (item) new Image().src = item.dataset.full;
  }

  function showPhoto(index) {
    currentIndex = index;
    const item = galleryItems[index];
    const text = () => {
      lightboxTitle.textContent = item.dataset.title;
      lightboxCaption.textContent = item.dataset.caption;
      lightboxCounter.textContent = (index + 1) + ' / ' + galleryItems.length;
      lightbox.classList.remove('loading');
    };
    if (lightboxImg.getAttribute('src') === item.dataset.full && lightboxImg.complete) {
      text();
    } else {
      // keep text and picture in step: swap the text once the new picture is ready
      lightbox.classList.add('loading');
      lightboxImg.onload = lightboxImg.onerror = text;
      lightboxImg.src = item.dataset.full;
    }
    lightboxImg.alt = item.querySelector('img').alt;
    preload(index + 1);
    preload(index - 1);
  }

  function openViewer(index) {
    if (!lightbox.classList.contains('active')) {
      returnFocus = document.activeElement;
      lightbox.classList.add('active');
      lightbox.setAttribute('aria-hidden', 'false');
      document.body.style.overflow = 'hidden';
      lightbox.querySelector('.lightbox-close').focus({ preventScroll: true });
    }
    showPhoto(index);
  }

  function hideViewer() {
    if (!lightbox.classList.contains('active')) return;
    lightbox.classList.remove('active');
    lightbox.setAttribute('aria-hidden', 'true');
    document.body.style.overflow = '';
    currentIndex = -1;
    if (returnFocus) returnFocus.focus({ preventScroll: true });
  }

  function photoHref(index) {
    return location.pathname + location.search + '#' + encodeURIComponent(galleryItems[index].dataset.id);
  }

  function openLightbox(index) {
    history.pushState({ photo: true, pushed: true }, '', photoHref(index));
    openViewer(index);
  }

  function closeLightbox() {
    if (history.state && history.state.pushed) {
      history.back(); // popstate hides the viewer
    } else {
      // opened from a shared link: drop the #photo without leaving the site
      history.replaceState(null, '', location.pathname + location.search);
      hideViewer();
    }
  }

  function navigate(dir) {
    const index = (currentIndex + dir + galleryItems.length) % galleryItems.length;
    history.replaceState({ ...history.state, photo: true }, '', photoHref(index));
    showPhoto(index);
  }

  function indexFromHash() {
    const id = decodeURIComponent(location.hash.slice(1));
    return galleryItems.findIndex(item => item.dataset.id === id);
  }

  window.addEventListener('popstate', () => {
    const index = indexFromHash();
    if (index >= 0) openViewer(index); else hideViewer();
  });

  galleryGrid.addEventListener('click', (e) => {
    const item = e.target.closest('.gallery-item');
    if (item) openLightbox(Math.max(0, galleryItems.indexOf(item)));
  });

  galleryGrid.addEventListener('keydown', (e) => {
    const item = e.target.closest('.gallery-item');
    if (item && (e.key === 'Enter' || e.key === ' ')) {
      e.preventDefault();
      openLightbox(galleryItems.indexOf(item));
    }
  });

  lightbox.querySelector('.lightbox-close').addEventListener('click', closeLightbox);
  lightbox.querySelector('.lightbox-prev').addEventListener('click', (e) => { e.stopPropagation(); navigate(-1); });
  lightbox.querySelector('.lightbox-next').addEventListener('click', (e) => { e.stopPropagation(); navigate(1); });
  lightbox.addEventListener('click', (e) => { if (e.target === lightbox) closeLightbox(); });

  // Swipe left/right to change photo on touch screens (the arrows are hidden on phones).
  let touchStart = null;
  lightbox.addEventListener('touchstart', (e) => {
    touchStart = { x: e.touches[0].clientX, y: e.touches[0].clientY };
  }, { passive: true });
  lightbox.addEventListener('touchend', (e) => {
    if (!touchStart) return;
    const dx = e.changedTouches[0].clientX - touchStart.x;
    const dy = e.changedTouches[0].clientY - touchStart.y;
    touchStart = null;
    if (Math.abs(dx) > 50 && Math.abs(dx) > Math.abs(dy)) navigate(dx < 0 ? 1 : -1);
  });

  document.addEventListener('keydown', (e) => {
    if (!lightbox.classList.contains('active')) return;
    if (e.key === 'Escape') closeLightbox();
    if (e.key === 'ArrowLeft') navigate(-1);
    if (e.key === 'ArrowRight') navigate(1);
    if (e.key === 'Tab') { // keep keyboard focus inside the viewer
      const buttons = [...lightbox.querySelectorAll('button')].filter(b => b.offsetParent !== null);
      const i = buttons.indexOf(document.activeElement);
      e.preventDefault();
      buttons[(i + (e.shiftKey ? -1 : 1) + buttons.length) % buttons.length].focus();
    }
  });

  // ===== SCROLL REVEAL =====
  // Photos that come into view together fade in one after another (in reading
  // order); the delay restarts for every batch instead of growing down the page.
  const observer = new IntersectionObserver((entries) => {
    const appearing = entries.filter(entry => entry.isIntersecting).map(entry => entry.target);
    appearing.forEach(el => observer.unobserve(el));
    appearing.filter(el => !el.classList.contains('gallery-item')).forEach(el => el.classList.add('revealed'));
    appearing.filter(el => el.classList.contains('gallery-item'))
      .sort((a, b) => galleryItems.indexOf(a) - galleryItems.indexOf(b))
      .forEach((el, i) => {
        el.style.transitionDelay = (i * 0.08) + 's';
        el.classList.add('visible');
      });
  }, { threshold: 0.1, rootMargin: '0px 0px -40px 0px' });

  function initReveal() {
    document.querySelectorAll('.reveal, .gallery-item').forEach(el => observer.observe(el));
  }

  fetch('data/photos.json')
    .then(res => res.json())
    .then(data => {
      renderGallery(data.photos);
      const shared = indexFromHash();
      if (shared >= 0) openViewer(shared); // a link to one photo
    })
    .catch(err => console.error('Could not load data/photos.json', err))
    .finally(initReveal);

  // ===== ACTIVE NAV LINK =====
  const sections = document.querySelectorAll('section[id]');
  const navLinks = document.querySelectorAll('.nav-links a');

  window.addEventListener('scroll', () => {
    let current = '';
    sections.forEach(section => {
      const top = section.offsetTop - 200;
      if (window.scrollY >= top) current = section.getAttribute('id');
    });
    navLinks.forEach(link => {
      link.classList.toggle('active', link.getAttribute('href') === '#' + current);
    });
  });

  // ===== LANGUAGE TOGGLE =====
  const langToggle = document.getElementById('langToggle');
  let currentLang = localStorage.getItem('lang') || 'en';
  const enTextStore = new Map();
  const enHtmlStore = new Map();

  document.querySelectorAll('[data-zh]').forEach(el => {
    enTextStore.set(el, el.textContent);
  });
  document.querySelectorAll('[data-zh-html]').forEach(el => {
    enHtmlStore.set(el, el.innerHTML);
  });

  function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('lang', lang);
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    document.title = lang === 'zh' ? 'SUN \u2014 摄影' : 'SUN \u2014 Photography';
    langToggle.textContent = lang === 'zh' ? 'EN' : '\u4E2D\u6587';

    document.querySelectorAll('[data-zh]').forEach(el => {
      el.textContent = lang === 'zh' ? el.dataset.zh : enTextStore.get(el);
    });

    document.querySelectorAll('[data-zh-html]').forEach(el => {
      el.innerHTML = lang === 'zh' ? el.dataset.zhHtml : enHtmlStore.get(el);
    });

  }

  langToggle.addEventListener('click', () => {
    setLanguage(currentLang === 'en' ? 'zh' : 'en');
  });

  if (currentLang === 'zh') setLanguage('zh');
})();
